-- =============================================================================
-- SEARCH_TEXT MAINTENANCE TRIGGER
-- =============================================================================
-- Oracle original:
--     CREATE OR REPLACE TRIGGER trg_book_search_text
--     BEFORE INSERT OR UPDATE OF TITLE, AUTHOR, ISBN ON BOOKS
--     FOR EACH ROW
--     BEGIN
--       :NEW.SEARCH_TEXT := LOWER(:NEW.TITLE) || ' ' ||
--                           LOWER(NVL(:NEW.AUTHOR,'')) || ' ' ||
--                           LOWER(NVL(:NEW.ISBN,''));
--     END;
--
-- THREE Db2 differences, all of them load-bearing:
--
--  1. Db2 has no "BEFORE INSERT OR UPDATE" -- one trigger per event. Split into
--     two triggers with identical bodies.
--  2. :NEW.col becomes a REFERENCING NEW AS n correlation, assigned with
--     SET n.col = ... inside a compound body. Db2 permits assignment to the
--     new-row correlation only in a BEFORE trigger, which is what we have.
--  3. *** NULL CONCATENATION *** Oracle treats NULL as the empty string in ||,
--     so a NULL TITLE yields ' author isbn'. Db2 propagates NULL, so the same
--     row would set SEARCH_TEXT = NULL and silently disappear from search
--     results. TITLE is therefore wrapped in COALESCE as well -- the Oracle
--     original only wrapped AUTHOR and ISBN, which was a latent bug there and
--     a real one here.

CREATE OR REPLACE TRIGGER TRG_BOOK_SEARCH_TEXT_INS
    NO CASCADE BEFORE INSERT ON BOOKS
    REFERENCING NEW AS N
    FOR EACH ROW
    MODE DB2SQL
    SET N.SEARCH_TEXT = LOWER(COALESCE(N.TITLE,  '')) || ' ' ||
                        LOWER(COALESCE(N.AUTHOR, '')) || ' ' ||
                        LOWER(COALESCE(N.ISBN,   ''));

CREATE OR REPLACE TRIGGER TRG_BOOK_SEARCH_TEXT_UPD
    NO CASCADE BEFORE UPDATE OF TITLE, AUTHOR, ISBN ON BOOKS
    REFERENCING NEW AS N
    FOR EACH ROW
    MODE DB2SQL
    SET N.SEARCH_TEXT = LOWER(COALESCE(N.TITLE,  '')) || ' ' ||
                        LOWER(COALESCE(N.AUTHOR, '')) || ' ' ||
                        LOWER(COALESCE(N.ISBN,   ''));

-- =============================================================================
-- FULL-TEXT INDEX -- NOT CONVERTED
-- =============================================================================
-- Oracle original:
--     CREATE INDEX BOOKS_TEXT_IDX ON BOOKS(SEARCH_TEXT)
--     INDEXTYPE IS CTXSYS.CONTEXT
--     PARAMETERS ('SYNC (ON COMMIT)');
--
-- There is NO Db2 LUW equivalent available here:
--   * Db2 Text Search (CREATE INDEX ... FOR TEXT, via SYSTS_ADMIN_CMD) is a
--     separately installed and licensed component. It is NOT available on
--     Amazon RDS for Db2, and it is not enabled in a default LUW install.
--   * Net Search Extender is withdrawn.
--
-- Consequence for query rewriting: Oracle CONTAINS(SEARCH_TEXT, :q) > 0 and
-- SCORE(1) have no direct replacement. The portable substitute is a LIKE
-- predicate over the same SEARCH_TEXT column, which the plain B-tree index
-- IDX_BOOKS_SEARCH above can support for prefix matches (LIKE 'foo%') but not
-- for infix matches (LIKE '%foo%', which forces a scan). Relevance ranking is
-- lost entirely. This is the same substitution made in the application's
-- BookRepository.fullTextSearchBooks.
--
-- If ranked full-text search is a hard requirement, the options are Db2 Text
-- Search on self-managed LUW, or externalising search to OpenSearch.
-- =============================================================================

COMMIT;

CONNECT RESET;

