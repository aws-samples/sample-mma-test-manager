-- =============================================================================
-- Bob's Used Books workshop - Db2 LUW schema V2
-- Converted from 02_schema_oracle_v2.sql
-- =============================================================================
-- Listings model (no OFFERS table): BOOKS holds metadata only, LISTINGS holds
-- price / quantity / condition. 14 tables.
--
-- NOTE ON SCOPE: this is the *workshop demo* schema generation. It is NOT the
-- schema the bundled Spring Boot app validates against -- the app expects
-- BOOKS.NAME (not TITLE), an OFFERS table, and PRICE/QUANTITY inline on BOOKS.
-- See ../JavaBobsUsedBooks-Db2/src/main/resources/db/db2/02_schema_db2.sql for
-- the application schema. Do not load both into the same schema.
--
-- TYPE MAPPING APPLIED THROUGHOUT
--   NUMBER(19,0)          -> BIGINT
--   NUMBER(10,0)          -> INTEGER
--   NUMBER(38,2)          -> DECIMAL(31,2)   <-- Db2's maximum precision is 31,
--                                                not 38. Values above 10^29 in
--                                                a price/total would now
--                                                overflow. Harmless for this
--                                                data set; flagged because it
--                                                is a real narrowing.
--   NUMBER(1,0) + CHECK   -> SMALLINT + CHECK    (Db2 has no NUMBER(1); this is
--                                                also what Hibernate maps
--                                                Boolean to)
--   VARCHAR2(n CHAR)      -> VARCHAR(n)          (see CHAR SEMANTICS below)
--   VARCHAR2(n)           -> VARCHAR(n)
--   TIMESTAMP(6)          -> TIMESTAMP(6)
--   DATE                  -> DATE            <-- Oracle DATE carries a time
--                                                component; Db2 DATE does not.
--                                                Any time-of-day previously
--                                                stored in SHIPPED_DATE /
--                                                DELIVERED_DATE / CANCELLED_DATE
--                                                / PUBLISH_DATE / DATE_OF_BIRTH
--                                                is silently truncated.
--   BLOB                  -> BLOB            <-- Db2 BLOB requires an explicit
--                                                maximum length; 10M is used.
--   GENERATED BY DEFAULT AS IDENTITY -> same (Db2 supports this verbatim, and
--                                       BY DEFAULT is required because the seed
--                                       data inserts explicit ID values)
--
-- CHAR SEMANTICS: Oracle VARCHAR2(255 CHAR) is 255 *characters*. Db2
-- VARCHAR(255) is 255 *bytes*. For multi-byte (non-ASCII) content use
-- VARCHAR(255 CODEUNITS32), which reserves 255 characters at the cost of 4x
-- byte width. Left as bytes here because the demo data is ASCII; switch to
-- CODEUNITS32 if real user-generated content will be loaded.
--
-- ORACLE NOISE REMOVED: ENABLE, USING INDEX, NOORDER, NOKEEP, NOSCALE,
-- CACHE 20 -- no Db2 analogue or not meaningful.
--
-- Run as DEMO:  db2 -tvf 02_schema_db2_v2.sql
-- =============================================================================

CONNECT TO BOBSDB USER DEMO USING <DEMO_PASSWORD>;

-- Oracle: ALTER SESSION SET CURRENT_SCHEMA=demo
SET CURRENT SCHEMA DEMO;
SET PATH = SYSIBM, SYSFUN, SYSPROC, SYSIBMADM, DEMO;

