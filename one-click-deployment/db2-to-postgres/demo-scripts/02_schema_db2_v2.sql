-- =============================================================================
-- BOOKS (metadata only -- inventory lives in LISTINGS)
-- =============================================================================
-- YEAR was NUMBER(10,0). "YEAR" is a Db2 built-in scalar function name but is
-- NOT a reserved word, so it is legal as a column name unqualified. It is left
-- as YEAR to keep the column contract identical to Oracle.

CREATE TABLE BOOKS (
    ID            BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1 NO CYCLE),
    TITLE         VARCHAR(255),
    AUTHOR        VARCHAR(255),
    ISBN          VARCHAR(255),
    DESCRIPTION   VARCHAR(1000),
    PUBLISH_DATE  DATE,
    YEAR          INTEGER,
    CREATED_ON    TIMESTAMP(6),
    UPDATED_ON    TIMESTAMP(6),
    CREATED_BY    VARCHAR(255),
    GENRE_ID      BIGINT,
    PUBLISHER_ID  BIGINT,
    BOOK_TYPE_ID  BIGINT,
    SEARCH_TEXT   VARCHAR(1000),
    PRIMARY KEY (ID),
    CONSTRAINT FK_BOOKS_BOOK_TYPE FOREIGN KEY (BOOK_TYPE_ID) REFERENCES BOOK_TYPES (ID),
    CONSTRAINT FK_BOOKS_GENRE     FOREIGN KEY (GENRE_ID)     REFERENCES GENRES (ID),
    CONSTRAINT FK_BOOKS_PUBLISHER FOREIGN KEY (PUBLISHER_ID) REFERENCES PUBLISHERS (ID)
) IN DEMOTBS;

-- =============================================================================
-- BOOKS_COVER (BLOB storage)
-- =============================================================================
-- Oracle "BLOB" is unbounded (4 GB). Db2 requires an explicit maximum length,
-- defaulting to 1 MB if omitted -- too small: the largest seeded cover is
-- ~120 KB, but 10M gives room for real cover art.
--
-- NOT LOGGED reduces log pressure for large LOBs but makes the column
-- non-recoverable by rollforward; left logged (the default) for safety.
-- Add COMPACT if storage matters more than read speed.

CREATE TABLE BOOKS_COVER (
    BOOK_ID       BIGINT NOT NULL,
    COVER_IMAGE   BLOB(10M),
    CONTENT_TYPE  VARCHAR(100),
    FILE_NAME     VARCHAR(255),
    CREATED_ON    TIMESTAMP(6),
    UPDATED_ON    TIMESTAMP(6),
    PRIMARY KEY (BOOK_ID),
    CONSTRAINT FK_BOOKS_COVER_BOOK FOREIGN KEY (BOOK_ID) REFERENCES BOOKS (ID) ON DELETE CASCADE
) IN DEMOTBS;

-- =============================================================================
-- CUSTOMERS
-- =============================================================================
-- Oracle's anonymous CHECK constraints are named here; Db2 auto-generates
-- opaque names otherwise, which makes later ALTER/DROP awkward.
-- ROLE is not reserved in Db2 (CREATE ROLE is a statement, not a keyword
-- restriction on identifiers), so the column name is kept.

CREATE TABLE CUSTOMERS (
    ID                  BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1 NO CYCLE),
    USERNAME            VARCHAR(255),
    EMAIL               VARCHAR(255),
    FIRST_NAME          VARCHAR(255),
    LAST_NAME           VARCHAR(255),
    PHONE_NUMBER        VARCHAR(255),
    PASSWORD_HASH       VARCHAR(255),
    SUB                 VARCHAR(255),
    DATE_OF_BIRTH       DATE,
    CREATED_ON          TIMESTAMP(6),
    EMAIL_VERIFIED      SMALLINT DEFAULT 0,
    ROLE                VARCHAR(255),
    ACCOUNT_EXPIRED     SMALLINT DEFAULT 0,
    CREDENTIALS_EXPIRED SMALLINT DEFAULT 0,
    ACCOUNT_LOCKED      SMALLINT DEFAULT 0,
    LAST_LOGIN          TIMESTAMP(6),
    PRIMARY KEY (ID),
    CONSTRAINT CK_CUST_ACCT_EXPIRED  CHECK (ACCOUNT_EXPIRED     IN (0,1)),
    CONSTRAINT CK_CUST_ACCT_LOCKED   CHECK (ACCOUNT_LOCKED      IN (0,1)),
    CONSTRAINT CK_CUST_CRED_EXPIRED  CHECK (CREDENTIALS_EXPIRED IN (0,1)),
    CONSTRAINT CK_CUST_EMAIL_VERIF   CHECK (EMAIL_VERIFIED      IN (0,1))
) IN DEMOTBS;

