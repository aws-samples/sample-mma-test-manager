    'Db2 LUW to PostgreSQL DDL Conversion Best Practices',
    'General guidelines for converting Db2 LUW DDL to PostgreSQL',
    'db2',
    'postgres',
    'Best Practices for Db2 LUW to PostgreSQL DDL Conversion:

1. Data Type Mappings:
   - SMALLINT → SMALLINT
   - INTEGER/INT → INTEGER
   - BIGINT → BIGINT
   - DECIMAL(p,s)/NUMERIC(p,s) → NUMERIC(p,s)
   - DECIMAL(31,2) → NUMERIC(31,2) (Db2 max precision is 31, PostgreSQL allows more)
   - DECFLOAT → NUMERIC (no direct equivalent; DECFLOAT(16|34) is IEEE decimal)
   - REAL → REAL
   - DOUBLE/FLOAT → DOUBLE PRECISION
   - CHAR(n) → CHAR(n)
   - VARCHAR(n) → VARCHAR(n)
   - CLOB(n) → TEXT
   - GRAPHIC/VARGRAPHIC/DBCLOB → CHAR/VARCHAR/TEXT (PostgreSQL is UTF-8 native)
   - BLOB(n) → BYTEA (Db2 requires an explicit maximum, e.g. BLOB(10M); BYTEA does not)
   - DATE → DATE
   - TIME → TIME
   - TIMESTAMP(p) → TIMESTAMP(p) (Db2 default precision is 6, same as PostgreSQL)
   - XML → XML
   - BOOLEAN → BOOLEAN
   - ROWID → no equivalent; use a surrogate key

2. Identity and Sequences:
   - GENERATED BY DEFAULT AS IDENTITY → GENERATED BY DEFAULT AS IDENTITY (PG 10+)
   - GENERATED ALWAYS AS IDENTITY → GENERATED ALWAYS AS IDENTITY
   - Db2 (START WITH n INCREMENT BY n NO CYCLE) maps directly
   - ALTER TABLE t ALTER COLUMN c RESTART WITH n
       → ALTER TABLE t ALTER COLUMN c RESTART WITH n
   - NEXT VALUE FOR seq → nextval(''seq'')
   - PREVIOUS VALUE FOR seq → currval(''seq'')

3. Syntax Conversions:
   - CURRENT DATE / CURRENT TIME / CURRENT TIMESTAMP → CURRENT_DATE / CURRENT_TIME / CURRENT_TIMESTAMP
   - VALUES expr (as a statement) → SELECT expr
   - SELECT ... FROM SYSIBM.SYSDUMMY1 → SELECT ... (PostgreSQL needs no dummy table)
   - FETCH FIRST n ROWS ONLY → LIMIT n (or FETCH FIRST n ROWS ONLY, also valid in PG)
   - COALESCE/VALUE(a, b) → COALESCE(a, b)
   - NVL(a, b) → COALESCE(a, b)
   - LENGTH() → LENGTH() (for characters) / OCTET_LENGTH() (for bytes)
   - POSSTR(str, sub) / LOCATE(sub, str) → POSITION(sub IN str)
   - SUBSTR(str, start, len) → SUBSTRING(str FROM start FOR len)
   - str1 CONCAT str2 or str1 || str2 → str1 || str2
   - DAYS(d1) - DAYS(d2) → d1 - d2 (integer days)
   - d + n DAYS → d + n * INTERVAL ''1 day''
   - TIMESTAMP_FORMAT(s, fmt) → TO_TIMESTAMP(s, fmt)
   - VARCHAR_FORMAT(ts, fmt) → TO_CHAR(ts, fmt)
   - CAST(x AS type) → CAST(x AS type)
   - RAISE_ERROR(sqlstate, text) → RAISE EXCEPTION USING ERRCODE = sqlstate

4. Catalog Views (Db2 has no dba_*/all_* views):
   - SYSCAT.TABLES → information_schema.tables / pg_class
   - SYSCAT.COLUMNS → information_schema.columns
   - SYSCAT.INDEXES + SYSCAT.INDEXCOLUSE → pg_indexes
   - SYSCAT.ROUTINES → information_schema.routines
   - SYSCAT.TRIGGERS → information_schema.triggers
   - SYSCAT.REFERENCES → information_schema.referential_constraints
   - SYSCAT.SEQUENCES → information_schema.sequences
   NOTE: on RDS for Db2, a non-administrative user may have no SELECT on SYSCAT.
   The master user does. Queries against SYSCAT fail with SQLCODE=-551
   (SQLSTATE 42501) for users without that privilege.

5. Routines and Packages:
   - Db2 has CREATE MODULE, but Oracle-style packages are usually flattened:
     pkg.routine → PKG_ROUTINE. Keep the naming consistent so callers resolve.
   - CREATE PROCEDURE p(...) LANGUAGE SQL BEGIN ... END
       → CREATE OR REPLACE PROCEDURE p(...) LANGUAGE plpgsql AS $$ BEGIN ... END; $$
   - Scalar function: BEGIN RETURN expr; END is valid in Db2 and maps to plpgsql.
   - TABLE function: a Db2 SQL table function body is a BARE `RETURN <select>`
     directly after the options, NOT wrapped in BEGIN ... END. Wrapping it fails
     with SQLCODE=-104 (SQLSTATE 42601), because a compound statement can only
     return a scalar. In PostgreSQL the equivalent is
     RETURNS TABLE(...) ... AS $$ BEGIN RETURN QUERY SELECT ...; END; $$
   - Db2 functions have no parameter defaults. A defaulted Oracle argument is
     commonly expressed as a 0-argument overload; PostgreSQL supports DEFAULT
     directly, so overloads can be collapsed back.
   - Error signalling: Db2 uses SIGNAL SQLSTATE ''75001'' SET MESSAGE_TEXT = ...
       → RAISE EXCEPTION ''...'' USING ERRCODE = ''75001''

6. Statement Terminators in Scripts:
   - Routine bodies contain inner semicolons, so scripts declare an alternative
     terminator: --#SET TERMINATOR # ... then END#
   - Strip these directives when converting; PostgreSQL uses $$ quoting instead.

7. Connection Statements:
   - CONNECT TO db USER u USING p / CONNECT RESET are CLP-only and have no JDBC
     equivalent. Remove them; the connection comes from the JDBC URL.

8. RDS for Db2 Specifics (source side):
   - CREATE BUFFERPOOL / CREATE TABLESPACE are unavailable to the master user
     (no SYSADM/SYSCTRL). Use rdsadmin.create_tablespace and related procedures,
     which only resolve while connected to the RDSADMIN database.
   - Users are database-authenticated via rdsadmin.add_user, not OS users.
   - SYSPROC.ADMIN_CMD (used for RUNSTATS, REORG) is not executable by ordinary
     users; the ROLE_PROCEDURES role covers SYSIBM, not SYSPROC.',
