    'Procedure Testing Strategy with Transaction Rollback:

1. Test Pattern for Data-Modifying Procedures:
   - Query relevant tables BEFORE procedure execution to capture initial state
   - Execute the procedure being tested
   - Query the same tables AFTER procedure execution to verify changes
   - ROLLBACK the transaction to restore the original data state

2. Db2 LUW Syntax for Testing:
   a) Simple query-execute-query pattern:
      SELECT COUNT(*) AS BEFORE_COUNT FROM SCHEMA.TABLE WHERE CONDITION;
      CALL SCHEMA.PROCEDURE_NAME(value1, value2);
      SELECT COUNT(*) AS AFTER_COUNT FROM SCHEMA.TABLE WHERE CONDITION;
      ROLLBACK;

   b) Reading OUT parameters:
      Db2 CALL returns OUT parameters to the client rather than into session
      variables, so capture them from the CALL result set. Over JDBC use
      CallableStatement with registerOutParameter.

   c) CRITICAL: Db2 LUW syntax rules:
      - Use CALL for procedure invocation (there is no EXEC)
      - Autocommit is ON by default over JDBC/CLP: disable it before the test,
        or the ROLLBACK has nothing to undo
        (JDBC: conn.setAutoCommit(false); CLP: UPDATE COMMAND OPTIONS USING C OFF)
      - Parameters are positional: CALL p(1, ''x'') - there is no @name = value form
      - Variables exist only inside a compound block (BEGIN ... END), not at
        statement level
      - Statements terminate with ; unless the script sets an alternative
        terminator via --#SET TERMINATOR

3. PostgreSQL Syntax for Testing:
   BEGIN;
   SELECT COUNT(*) AS before_count FROM schema.table WHERE condition;
   CALL schema.procedure_name(param1, param2);
   SELECT COUNT(*) AS after_count FROM schema.table WHERE condition;
   ROLLBACK;

4. Implementation Steps:
   a) Use the MCP server to query the initial data state
   b) Execute the procedure with test parameters
   c) Query the data again to verify the procedure effects
   d) ROLLBACK to undo all changes

