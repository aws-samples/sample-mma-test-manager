     rather than vendor error numbers
   - A Db2 function cannot perform INSERT/UPDATE/DELETE, so an Oracle function
     that modified data is commonly converted to a PROCEDURE with an OUT
     parameter. Test it as a procedure, not a function

6. Benefits:
